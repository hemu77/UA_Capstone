import {createRequire} from 'node:module';
import assert from 'node:assert/strict';
const require=createRequire(import.meta.url),{chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright');
const base=process.env.VIEWER_URL||'http://127.0.0.1:8781';
const browser=await chromium.launch({headless:true,channel:process.env.BROWSER_CHANNEL||'msedge'});
try{
  const page=await browser.newPage({viewport:{width:1440,height:1000}});
  const errors=[],requests=[];page.on('pageerror',e=>errors.push(e.message));page.on('request',r=>requests.push(r.url()));
  await page.goto(base+'/layers.html');await page.waitForSelector('#layers .select-run');
  assert.equal(requests.filter(u=>/saved-plots/.test(u)).length,0,'Gallery must not delay replay startup');
  await page.getByRole('link',{name:'896 saved plots'}).click();
  await page.waitForSelector('#plot-grid .plot-card');
  assert.equal(await page.locator('#plot-grid .plot-card').count(),8);
  assert.match(await page.locator('#plot-status').innerText(),/1-8 of 896/);
  await page.locator('#plot-page-next').click();assert.match(await page.locator('#plot-status').innerText(),/9-16 of 896/);
  await page.locator('#plot-cohort').selectOption('primary');assert.match(await page.locator('#plot-status').innerText(),/of 890/);
  await page.locator('#plot-method').selectOption('global');assert.match(await page.locator('#plot-status').innerText(),/of 219/);
  await page.locator('#plot-search').fill('gpt-4.1 english 44000');
  assert.equal(await page.locator('#plot-grid .plot-card').count(),4);
  await page.locator('#plot-clear').click();
  await page.locator('#plot-cohort').selectOption('supplement');assert.equal(await page.locator('#plot-grid .plot-card').count(),6);
  assert.ok((await page.locator('#plot-grid .plot-badge').allTextContents()).every(t=>t.includes('excluded from primary')));
  const selection=await page.locator('#layers').innerText(),frame=await page.locator('#timeline').inputValue();
  await page.locator('#plot-grid .plot-thumbnail').first().click();
  await page.waitForFunction(()=>{const i=document.querySelector('#plot-dialog-image img');return i?.complete&&i.naturalWidth>0;});
  assert.equal(await page.locator('#plot-dialog').evaluate(n=>n.open),true);
  assert.match(await page.locator('#plot-dialog-cohort').innerText(),/Supplement/);
  const first=await page.locator('#plot-original').getAttribute('href');
  await page.keyboard.press('ArrowRight');assert.notEqual(await page.locator('#plot-original').getAttribute('href'),first);
  assert.equal(await page.locator('#timeline').inputValue(),frame,'Gallery arrows must not seek replay');
  await page.keyboard.press('Escape');assert.equal(await page.locator('#plot-dialog').evaluate(n=>n.open),false);
  assert.equal(await page.locator('#layers').innerText(),selection,'Supplements must not enter 3D replay');
  await page.locator('#plot-search').fill('absent-test-id');assert.match(await page.locator('#plot-status').innerText(),/No matching/);
  await page.locator('#plot-clear').click();
  await page.setViewportSize({width:390,height:844});
  await page.locator('#plot-grid .plot-thumbnail').first().click();
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'Mobile gallery overflow');
  await page.screenshot({path:process.env.VIEWER_SCREENSHOT||'gallery-mobile-qa.png',fullPage:false});
  await page.keyboard.press('Escape');
  await page.route('**/data/saved-plots.json',r=>r.fulfill({status:503,body:'Unavailable'}));
  await page.reload();await page.waitForSelector('#plot-retry:not([hidden])');
  assert.match(await page.locator('#plot-status').innerText(),/could not be loaded/);
  await page.unroute('**/data/saved-plots.json');await page.locator('#plot-retry').click();
  await page.waitForSelector('#plot-grid .plot-card');assert.equal(await page.locator('#plot-grid .plot-card').count(),8);
  await page.route('**/data/saved-plots/*.png',r=>r.fulfill({status:404,body:'Missing'}));
  await page.locator('#plot-page-next').click();
  await page.waitForFunction(()=>document.querySelector('#plot-grid').textContent.includes('Image unavailable'));
  assert.ok(await page.locator('#plot-grid a').first().getAttribute('href'));
  assert.deepEqual(errors,[]);
  console.log('PASS: lazy 896-plot gallery, cohort/method/search filters, pagination, modal images/arrows/Escape, replay isolation, mobile, 503 recovery, missing-image fallback.');
}finally{await browser.close();}
